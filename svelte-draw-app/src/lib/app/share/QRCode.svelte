<script lang="ts">
  import Spinner from "@svelte-draw/editor/components/Spinner.svelte";

  let { value }: { value: string } = $props();

  let svgData = $state<string | null>(null);
  let error = $state(false);

  $effect(() => {
    const text = value;
    let mounted = true;

    import("./qrcode.chunk.ts")
      .then(({ generateQRCodeSVG }) => {
        if (mounted) {
          try {
            svgData = generateQRCodeSVG(text);
          } catch {
            error = true;
          }
        }
      })
      .catch(() => {
        if (mounted) {
          error = true;
        }
      });

    return () => {
      mounted = false;
    };
  });
</script>

{#if error}
  <!-- render nothing -->
{:else if !svgData}
  <div class="ShareDialog__active__qrcode ShareDialog__active__qrcode--loading">
    <Spinner />
  </div>
{:else}
  <div
    class="ShareDialog__active__qrcode"
    role="img"
    aria-label="QR code for collaboration link"
  >
    <!-- SVG generated by `uqr` from our own room link; not user markup -->
    <!-- eslint-disable-next-line svelte/no-at-html-tags -->
    {@html svgData}
  </div>
{/if}
